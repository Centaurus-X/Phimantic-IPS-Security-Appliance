def _parse_path(path_str):
    """Parsed 'a.b[c].d[e]' in Token-Liste.

    Tokens: ("attr", name) | ("list", key)
    """
    tokens = []
    pattern = re.compile(r"([A-Za-z_][A-Za-z0-9_\-]*)(?:\[([^\]]+)\])?")
    pos = 0
    while pos < len(path_str):
        if path_str[pos] == ".":
            pos += 1
            continue
        m = pattern.match(path_str, pos)
        if not m:
            return []
        name, key = m.group(1), m.group(2)
        tokens.append(("attr", name))
        if key is not None:
            tokens.append(("list", key))
        pos = m.end()
    return tokens


def _list_token_is_index(key):
    return isinstance(key, str) and key.isdigit()


def _get_by_tokens(data, tokens):
    cur = data
    for kind, key in tokens:
        if kind == "attr":
            if not isinstance(cur, dict) or key not in cur:
                return False, None
            cur = cur[key]
        elif kind == "list":
            if not isinstance(cur, list):
                return False, None
            if _list_token_is_index(key):
                idx = int(key)
                if idx < 0 or idx >= len(cur):
                    return False, None
                cur = cur[idx]
                continue
            found = None
            for item in cur:
                if isinstance(item, dict) and key in item:
                    found = item[key]
                    break
            if found is None:
                return False, None
            cur = found
    return True, cur


def _ensure_list_index(values, key):
    idx = int(key)
    while len(values) <= idx:
        values.append({})
    return idx


def _set_by_tokens(data, tokens, value):
    if not tokens:
        return False
    cur = data
    for i, (kind, key) in enumerate(tokens):
        is_last = (i == len(tokens) - 1)
        if kind == "attr":
            if is_last:
                if not isinstance(cur, dict):
                    return False
                cur[key] = value
                return True
            if not isinstance(cur, dict):
                return False
            if key not in cur:
                nxt_kind = tokens[i + 1][0] if i + 1 < len(tokens) else None
                cur[key] = [] if nxt_kind == "list" else {}
            cur = cur[key]
        elif kind == "list":
            if not isinstance(cur, list):
                return False
            if _list_token_is_index(key):
                idx = _ensure_list_index(cur, key)
                if is_last:
                    cur[idx] = value
                    return True
                if not isinstance(cur[idx], (dict, list)):
                    nxt_kind = tokens[i + 1][0] if i + 1 < len(tokens) else None
                    cur[idx] = [] if nxt_kind == "list" else {}
                cur = cur[idx]
                continue
            found_idx = -1
            for idx, item in enumerate(cur):
                if isinstance(item, dict) and key in item:
                    found_idx = idx
                    break
            if found_idx < 0:
                if is_last:
                    cur.append({key: value})
                    return True
                new_obj = {}
                cur.append({key: new_obj})
                cur = new_obj
            else:
                if is_last:
                    cur[found_idx][key] = value
                    return True
                if not isinstance(cur[found_idx][key], (dict, list)):
                    nxt_kind = tokens[i + 1][0] if i + 1 < len(tokens) else None
                    cur[found_idx][key] = [] if nxt_kind == "list" else {}
                cur = cur[found_idx][key]
    return True


def read_structured(cfg):
    from services.config_schema import get_schema

    raw = read_config(cfg)
    if not raw.get("ok"):
        return {"ok": False, "error": raw.get("error", "read_failed")}

    if not _YAML_OK:
        return {"ok": False, "error": "pyyaml_missing"}

    try:
        parsed = yaml.safe_load(raw["content"]) or {}
    except yaml.YAMLError as exc:
        return {"ok": False, "error": "yaml_parse_failed: " + str(exc)}

    schema = get_schema()
    values = {}
    for section in schema["sections"]:
        for field in section["fields"]:
            ftype = field["type"]
            path = field["path"]
            if ftype == "list-of-objects":
                if isinstance(parsed, dict) and path in parsed:
                    values[path] = parsed[path] or []
                else:
                    values[path] = []
                continue
            tokens = _parse_path(path)
            found, val = _get_by_tokens(parsed, tokens)
            values[path] = val if found else field.get("default")

    return {"ok": True, "schema": schema, "values": values,
            "path": raw.get("path"), "warnings": _detect_warnings(parsed, cfg),
            "phimantec_notice": cfg.get("phimantec", {}).get("proxy_safe_notice", "")}


def _find_named_item(items, name):
    if not isinstance(items, list):
        return None
    for item in items:
        if isinstance(item, dict) and name in item:
            return item[name]
    return None


def _eve_log_config(parsed):
    outputs = parsed.get("outputs") if isinstance(parsed, dict) else None
    eve = _find_named_item(outputs, "eve-log")
    return eve if isinstance(eve, dict) else None


def _eve_alert_config(parsed):
    eve = _eve_log_config(parsed)
    if not isinstance(eve, dict):
        return None
    alert = _find_named_item(eve.get("types"), "alert")
    return alert if isinstance(alert, dict) else None


def _truthy(value):
    if value is True:
        return True
    if isinstance(value, str) and value.lower() in ("yes", "true", "on", "1"):
        return True
    return False


def _detect_warnings(parsed, cfg=None):
    warnings = []
    if not isinstance(parsed, dict):
        warnings.append("Suricata-Konfiguration ist kein YAML-Mapping.")
        return warnings

    phim = cfg.get("phimantec", {}) if isinstance(cfg, dict) else {}
    local_rule = phim.get("local_rules_file", "phimantec-local.rules")
    expected_eve = phim.get("required_eve_file", "eve.json")

    rule_files = parsed.get("rule-files")
    if not isinstance(rule_files, list) or local_rule not in rule_files:
        warnings.append("PHIMANTEC-Regeldatei '{0}' fehlt in rule-files; Proxy-Verdicts koennen dadurch ausbleiben.".format(local_rule))

    eve = _eve_log_config(parsed)
    if eve is None:
        warnings.append("EVE-Log output 'eve-log' fehlt; inspectord braucht eve.json fuer die Flow-Korrelation.")
    else:
        if not _truthy(eve.get("enabled", True)):
            warnings.append("EVE-Log ist deaktiviert; PHIMANTEC inspectord kann dann keine Suricata-Alerts korrelieren.")
        filename = eve.get("filename")
        if filename and filename != expected_eve:
            warnings.append("EVE-Dateiname ist '{0}', erwartet wird fuer das Standardprofil '{1}'.".format(filename, expected_eve))

    alert = _eve_alert_config(parsed)
    if alert is None:
        warnings.append("EVE alert-Type fehlt; Suricata-Alerts erreichen die Proxy-Entscheidung dann nicht.")
    else:
        if not _truthy(alert.get("enabled", True)):
            warnings.append("EVE alert-Type ist deaktiviert; Blocking-Signale fehlen dann.")
        if not _truthy(alert.get("payload-printable", False)):
            warnings.append("alert.payload-printable ist deaktiviert; X-Phim-Flow-Id ist fuer inspectord dann nicht sicher sichtbar.")

    af_packet = parsed.get("af-packet")
    if not isinstance(af_packet, list) or len(af_packet) == 0:
        warnings.append("AF_PACKET-Capture ist nicht konfiguriert; fuer die Proxy-Lane muss Suricata das Lane-Interface beobachten.")
    else:
        for item in af_packet:
            if not isinstance(item, dict):
                continue
            copy_mode = str(item.get("copy-mode", "") or "")
            if copy_mode in ("tap", "ips"):
                warnings.append("AF_PACKET copy-mode={0} ist moeglich, aber fuer das PHIMANTEC Proxy-Lane-Profil normalerweise nicht empfohlen.".format(copy_mode))

    if isinstance(parsed.get("pf-ring"), dict):
        warnings.append("pf-ring-Konfiguration vorhanden - bitte nur bewusst ueber YAML-Tab editieren.")
    if isinstance(parsed.get("napatech"), dict):
        warnings.append("napatech-Konfiguration vorhanden - bitte nur bewusst ueber YAML-Tab editieren.")
    if isinstance(parsed.get("nflog"), list) and parsed["nflog"]:
        warnings.append("nflog-Konfiguration vorhanden; fuer die Standard-Proxy-Lane ist AF_PACKET vorgesehen.")
    if isinstance(parsed.get("nfqueue"), dict) or isinstance(parsed.get("nfq"), dict):
        warnings.append("NFQUEUE/IPS-Mode ist konfiguriert. Das ist moeglich, aber fuer den Proxy-Betrieb nicht der Standardpfad.")
    if isinstance(parsed.get("pcap"), list) and parsed["pcap"]:
        warnings.append("PCAP-Capture ist konfiguriert. Fuer performanten Docker-/VM-Betrieb bleibt AF_PACKET empfohlen.")
    if isinstance(parsed.get("dpdk"), dict):
        warnings.append("DPDK ist konfiguriert. Das ist ein Spezialprofil und sollte vom Proxy-Lane-Profil getrennt getestet werden.")

    mpm = str(parsed.get("mpm-algo", "") or "")
    spm = str(parsed.get("spm-algo", "") or "")
    if mpm not in ("hs", "auto", "") or spm not in ("hs", "auto", ""):
        warnings.append("Pattern-Matcher weicht von hs/auto ab. Funktional moeglich, aber Hyperscan bleibt fuer hohe Lane-Last empfohlen.")

    return warnings


def write_structured(cfg, updates, run_validate=True):
    if _is_mock(cfg):
        return {"ok": True, "mock": True,
                "message": "[mock] write_structured skipped",
                "applied": len(updates), "failed_paths": []}

    if not _YAML_OK:
        return {"ok": False, "error": "pyyaml_missing"}

    raw = read_config(cfg)
    if not raw.get("ok"):
        return {"ok": False, "error": raw.get("error", "read_failed")}

    try:
        parsed = yaml.safe_load(raw["content"]) or {}
    except yaml.YAMLError as exc:
        return {"ok": False, "error": "yaml_parse_failed: " + str(exc)}

    from services.config_schema import get_schema
    schema = get_schema()
    list_obj_paths = set()
    for section in schema["sections"]:
        for field in section["fields"]:
            if field["type"] == "list-of-objects":
                list_obj_paths.add(field["path"])

    applied = 0
    failed = []
    for path, value in updates.items():
        if path in list_obj_paths:
            parsed[path] = value
            applied += 1
            continue
        tokens = _parse_path(path)
        if not tokens:
            failed.append(path)
            continue
        if _set_by_tokens(parsed, tokens, value):
            applied += 1
        else:
            failed.append(path)

    try:
        new_content = yaml.dump(parsed, default_flow_style=False,
                                sort_keys=False, allow_unicode=True)
    except yaml.YAMLError as exc:
        return {"ok": False, "error": "yaml_dump_failed: " + str(exc)}

    if not new_content.startswith("%YAML"):
        new_content = "%YAML 1.1\n---\n" + new_content

    write_res = write_config(cfg, new_content, run_validate=run_validate)
    write_res["applied"] = applied
    write_res["failed_paths"] = failed
    return write_res


