def read_config(cfg):
    if _is_mock(cfg):
        return {"ok": True, "mock": True, "path": _config_path(cfg),
                "content": _MOCK_YAML, "size_bytes": len(_MOCK_YAML)}
    path = _config_path(cfg)
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            content = fh.read()
        return {"ok": True, "path": path, "content": content,
                "size_bytes": len(content)}
    except OSError as exc:
        return {"ok": False, "error": str(exc), "path": path}


def write_config(cfg, content, run_validate=True):
    if _is_mock(cfg):
        return {"ok": True, "mock": True,
                "message": "[mock] write_config skipped"}
    path = _config_path(cfg)
    backup = path + ".bak." + time.strftime("%Y%m%d-%H%M%S")
    try:
        if os.path.isfile(path):
            shutil.copy2(path, backup)
    except OSError as exc:
        return {"ok": False, "error": "backup_failed: " + str(exc)}

    tmp = path + ".tmp"
    try:
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(content)
        if run_validate:
            res = validate(cfg, config_path_override=tmp)
            if not res["ok"]:
                try:
                    os.remove(tmp)
                except OSError:
                    pass
                return {"ok": False, "error": "validation_failed",
                        "details": res.get("message", "")}
        os.replace(tmp, path)
        result = {"ok": True, "backup": backup, "path": path}
        persist = _persist_phimantec_runtime_state(cfg, path, content)
        if persist.get("ok"):
            result["persisted"] = persist
        else:
            result["persist_warning"] = persist.get("error", "persist_failed")
        return result
    except OSError as exc:
        return {"ok": False, "error": str(exc)}


def validate(cfg, config_path_override=None):
    if _is_mock(cfg):
        return {"ok": True, "mock": True, "message": "[mock] valid"}
    path = config_path_override or _config_path(cfg)
    try:
        proc = subprocess.run(
            ["suricata", "-T", "-c", path],
            capture_output=True, text=True, timeout=60,
        )
        return {"ok": proc.returncode == 0,
                "message": (proc.stderr or proc.stdout).strip()}
    except (subprocess.TimeoutExpired, OSError) as exc:
        return {"ok": False, "message": str(exc)}


