_SUMMARY_KEYS = [
    ("default-log-dir", r"^\s*default-log-dir\s*:\s*(.+)$"),
    ("default-rule-path", r"^\s*default-rule-path\s*:\s*(.+)$"),
    ("mpm-algo", r"^\s*mpm-algo\s*:\s*(\S+)"),
    ("spm-algo", r"^\s*spm-algo\s*:\s*(\S+)"),
    ("runmode", r"^\s*runmode\s*:\s*(\S+)"),
]


def get_summary(cfg):
    res = read_config(cfg)
    if not res.get("ok"):
        return res
    content = res["content"]
    summary = {}
    for key, pattern in _SUMMARY_KEYS:
        m = re.search(pattern, content, re.MULTILINE)
        summary[key] = m.group(1).strip() if m else None
    iface_matches = re.findall(r"^\s*-\s*interface\s*:\s*(\S+)",
                               content, re.MULTILINE)
    summary["af_packet_interfaces"] = list(dict.fromkeys(iface_matches))
    summary["path"] = res.get("path")
    summary["size_bytes"] = res.get("size_bytes", 0)
    return {"ok": True, "summary": summary}


