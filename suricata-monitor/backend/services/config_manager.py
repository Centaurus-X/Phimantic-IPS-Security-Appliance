"""Suricata YAML-Config-Manager.

Drei API-Ebenen:
    1. Raw-Text-Ebene: read_config / write_config (bewahrt Kommentare)
    2. Strukturiert:   read_structured / write_structured (Schema-basiert)
    3. Summary:        get_summary (Best-Effort-Read-Only)
"""

import os
import re
import shutil
import subprocess
import time

try:
    import yaml
    _YAML_OK = True
except ImportError:
    _YAML_OK = False


def _is_mock(cfg):
    return bool(cfg.get("suricata", {}).get("mock_mode", False))


def _config_path(cfg):
    return cfg["suricata"]["config_path"]


def _phimantec_state_dir(cfg):
    phim = cfg.get("phimantec", {}) if isinstance(cfg, dict) else {}
    value = phim.get("state_dir")
    if isinstance(value, str) and value.strip():
        return value.strip()
    db_path = cfg.get("database", {}).get("path") if isinstance(cfg, dict) else None
    if isinstance(db_path, str) and db_path.strip():
        return os.path.dirname(db_path.strip()) or "/var/lib/suricata-monitor"
    return "/var/lib/suricata-monitor"


def _persisted_config_path(cfg):
    phim = cfg.get("phimantec", {}) if isinstance(cfg, dict) else {}
    value = phim.get("persisted_config_path")
    if isinstance(value, str) and value.strip():
        return value.strip()
    return os.path.join(_phimantec_state_dir(cfg), "suricata.yaml.persisted")


def _runtime_override_path(cfg):
    phim = cfg.get("phimantec", {}) if isinstance(cfg, dict) else {}
    value = phim.get("runtime_override_path")
    if isinstance(value, str) and value.strip():
        return value.strip()
    return os.path.join(_phimantec_state_dir(cfg), "phimantec-runtime-overrides.env")


def _first_af_packet(parsed):
    values = parsed.get("af-packet") if isinstance(parsed, dict) else None
    if isinstance(values, list) and values and isinstance(values[0], dict):
        return values[0]
    return {}


def _runtime_string(value, default):
    if value is None:
        return str(default)
    text = str(value).strip()
    return text if text else str(default)




def _http_body_limit(parsed):
    if not isinstance(parsed, dict):
        return 1048576
    app_layer = parsed.get("app-layer")
    if not isinstance(app_layer, dict):
        return 1048576
    protocols = app_layer.get("protocols")
    if not isinstance(protocols, dict):
        return 1048576
    http = protocols.get("http")
    if not isinstance(http, dict):
        return 1048576
    libhtp = http.get("libhtp")
    if not isinstance(libhtp, dict):
        return 1048576
    default_config = libhtp.get("default-config")
    if not isinstance(default_config, dict):
        return 1048576
    value = default_config.get("request-body-limit", 1048576)
    try:
        parsed_value = int(value)
    except (TypeError, ValueError):
        parsed_value = 1048576
    if parsed_value < 4096:
        return 1048576
    return parsed_value

def _write_runtime_overrides(cfg, parsed):
    af_packet = _first_af_packet(parsed)
    values = {
        "PHIMANTEC_SURICATA_INTERFACE": _runtime_string(af_packet.get("interface"), "auto"),
        "PHIMANTEC_SURICATA_MPM": _runtime_string(parsed.get("mpm-algo") if isinstance(parsed, dict) else None, "hs"),
        "PHIMANTEC_SURICATA_SPM": _runtime_string(parsed.get("spm-algo") if isinstance(parsed, dict) else None, "hs"),
        "PHIMANTEC_SURICATA_RUNMODE": _runtime_string(parsed.get("runmode") if isinstance(parsed, dict) else None, "workers"),
        "PHIMANTEC_SURICATA_AF_PACKET_THREADS": _runtime_string(af_packet.get("threads"), "auto"),
        "PHIMANTEC_SURICATA_BODY_LIMIT": _runtime_string(_http_body_limit(parsed), "1048576"),
    }
    path = _runtime_override_path(cfg)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write("# Generated by SuricataMonitor. Values are loaded by docker_suricata_node_entrypoint.sh.\n")
        for key in sorted(values):
            handle.write("{0}={1}\n".format(key, values[key]))
    os.replace(tmp, path)
    return path


def _persist_phimantec_runtime_state(cfg, source_path, content):
    result = {"ok": True}
    if _is_mock(cfg):
        result["mock"] = True
        return result
    if not _YAML_OK:
        return {"ok": False, "error": "pyyaml_missing"}
    try:
        parsed = yaml.safe_load(content) or {}
    except yaml.YAMLError as exc:
        return {"ok": False, "error": "yaml_parse_failed: " + str(exc)}
    try:
        persisted_path = _persisted_config_path(cfg)
        os.makedirs(os.path.dirname(persisted_path), exist_ok=True)
        shutil.copy2(source_path, persisted_path)
        result["persisted_config_path"] = persisted_path
        result["runtime_override_path"] = _write_runtime_overrides(cfg, parsed)
        return result
    except OSError as exc:
        return {"ok": False, "error": "persist_failed: " + str(exc)}


